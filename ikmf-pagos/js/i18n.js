function getLang() {
  let saved = null;
  try { saved = localStorage.getItem(LANG_KEY); } catch { /* sin storage */ }
  if (saved && LANGS[saved]) return saved;
  const nav = (navigator.language || "es").slice(0, 2).toLowerCase();
  if (nav === "iw") return "he";
  return LANGS[nav] ? nav : "es";
}

function setLang(code) {
  if (!LANGS[code]) return;
  try { localStorage.setItem(LANG_KEY, code); } catch { /* sin storage */ }
  location.reload();
}

function currentLocale() {
  return LANGS[getLang()].locale;
}

function t(key, vars) {
  const lang = getLang();
  let str = (DICT[lang] && DICT[lang][key]) || DICT.es[key] || key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      str = str.split(`{${k}}`).join(vars[k] == null ? "" : vars[k]);
    });
  }
  return str;
}

// Traduce los elementos con data-i18n / data-i18n-ph dentro de `root`.
function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
}

function langSelectHTML(id) {
  const cur = getLang();
  return `<select class="lang-select" id="${id}" aria-label="${t("lang.label")}">
    ${Object.entries(LANGS).map(([code, l]) => `<option value="${code}" ${code === cur ? "selected" : ""}>${l.label}</option>`).join("")}
  </select>`;
}

function bindLangSelect(el) {
  if (el) el.addEventListener("change", () => setLang(el.value));
}

(function initLang() {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.documentElement.dir = LANGS[lang].dir;
})();
